Q_TRUTH = np.asarray([0.025, 0.014, 0.022], dtype=float)
Q_SCALES = np.asarray([0.05, 0.015, 0.025], dtype=float)
PARAM_NAMES = (r"$J_{12}$", r"$k_{12}$", r"$\gamma_\phi$")
PARAM_UNITS = ("eV", "time$^{-1}$", "time$^{-1}$")
FIXED = {
    "omega_1": 1.0, "omega_2": 1.18, "anharmonicity": -0.06,
    "gamma_1": 0.03, "gamma_2": 0.004, "beta_12": 2.5,
    "mu_1": 1.0, "mu_2": 1.0, "mu_esa_scale": 1.0,
}


def _op(i: int, j: int, n: int = 4):
    return np.eye(n, dtype=complex)[:, i:i+1] @ np.eye(n, dtype=complex)[:, j:j+1].conj().T


def _dissipator(c):
    return general.lindblad_dissipator(c)


def _candidate_model():
    ref = {**FIXED, "J_12": Q_TRUTH[0], "k_12": Q_TRUTH[1], "gamma_phi": Q_TRUTH[2]}
    pmap = general.ParameterMap(
        reference_params=ref,
        controls=tuple(
            general.ControlSpec(name, float(value), float(scale))
            for name, value, scale in zip(("J_12", "k_12", "gamma_phi"), Q_TRUTH, Q_SCALES, strict=True)
        ),
    )

    def ham(p):
        p0, p1, p2, p3 = (_op(i, i) for i in range(4))
        return (p["omega_1"]*p1 + p["omega_2"]*p2
                + (p["omega_1"] + p["omega_2"] + p["anharmonicity"])*p3
                + p["J_12"]*(_op(1, 2) + _op(2, 1)))

    def collapses(p):
        out = []
        for rate, i, k in ((p["gamma_1"],0,1),(p["gamma_1"],2,3),
                           (p["gamma_2"],0,2),(p["gamma_2"],1,3)):
            out.append(np.sqrt(rate)*_op(i,k))
        detuning = p["omega_2"] - p["omega_1"]
        out.append(np.sqrt(p["k_12"]*np.exp(-.5*p["beta_12"]*detuning))*_op(2,1))
        out.append(np.sqrt(p["k_12"]*np.exp(+.5*p["beta_12"]*detuning))*_op(1,2))
        z = np.diag([-2., 0., 0., 2.]).astype(complex)
        out.append(np.sqrt(p["gamma_phi"])*z)
        return out

    def mu_plus(p):
        return (p["mu_1"]*_op(1,0) + p["mu_2"]*_op(2,0)
                + p["mu_esa_scale"]*p["mu_2"]*_op(3,1)
                + p["mu_esa_scale"]*p["mu_1"]*_op(3,2))

    model = general.LiouvilleModel.from_hamiltonian(
        dimension=4, hamiltonian=ham, collapse_ops=collapses,
        initial_state=lambda _p: general.vec(_op(0,0)),
        transition_dipole=lambda p: mu_plus(p) + mu_plus(p).conj().T,
        dipole_components=lambda p: (mu_plus(p), mu_plus(p).conj().T),
    )
    return model, pmap


def _jax_liouvillian_from_lambda(pmap):
    def op(i, j):
        return jnp.zeros((4,4),dtype=jnp.complex128).at[i,j].set(1.)
    eye = jnp.eye(4,dtype=jnp.complex128)
    def diss(c):
        cdc=c.conj().T@c
        return jnp.kron(c.conj(),c)-.5*jnp.kron(eye,cdc)-.5*jnp.kron(cdc.T,eye)
    def from_lambda(lam):
        q=jnp.asarray(Q_TRUTH)+jnp.asarray(Q_SCALES)*lam
        j,k,gamma=q
        w1,w2=FIXED["omega_1"],FIXED["omega_2"]
        p1,p2,p3=op(1,1),op(2,2),op(3,3)
        h=(w1*p1+w2*p2+(w1+w2+FIXED["anharmonicity"])*p3
           +j*(op(1,2)+op(2,1)))
        l=-1j*(jnp.kron(eye,h)-jnp.kron(h.T,eye))
        l=l+FIXED["gamma_1"]*(diss(op(0,1))+diss(op(2,3)))
        l=l+FIXED["gamma_2"]*(diss(op(0,2))+diss(op(1,3)))
        delta=w2-w1; beta=FIXED["beta_12"]
        l=l+k*jnp.exp(-.5*beta*delta)*diss(op(2,1))
        l=l+k*jnp.exp(+.5*beta*delta)*diss(op(1,2))
        z=jnp.diag(jnp.asarray([-2.,0.,0.,2.],dtype=jnp.complex128))
        return l+gamma*diss(z)
    return from_lambda


def _truth_full_model(kd: float):
    """Five-state TP Lindblad truth with a dark terminal sink."""
    q=Q_TRUTH
    p={**FIXED,"J_12":q[0],"k_12":q[1],"gamma_phi":q[2],"k_d":kd}
    def op(i,j): return _op(i,j,5)
    def ham(params):
        p1,p2,p3=op(1,1),op(2,2),op(3,3)
        return (params["omega_1"]*p1+params["omega_2"]*p2
                +(params["omega_1"]+params["omega_2"]+params["anharmonicity"])*p3
                +params["J_12"]*(op(1,2)+op(2,1)))
    def collapses(params):
        out=[np.sqrt(params["gamma_1"])*op(0,1),np.sqrt(params["gamma_1"])*op(2,3),
             np.sqrt(params["gamma_2"])*op(0,2),np.sqrt(params["gamma_2"])*op(1,3)]
        d=params["omega_2"]-params["omega_1"]
        out.extend([np.sqrt(params["k_12"]*np.exp(-.5*params["beta_12"]*d))*op(2,1),
                    np.sqrt(params["k_12"]*np.exp(+.5*params["beta_12"]*d))*op(1,2)])
        out.append(np.sqrt(params["gamma_phi"])*np.diag([-2.,0.,0.,2.,0.]))
        out.append(np.sqrt(params["k_d"])*op(4,1))
        return out
    def mu_plus(params):
        return (params["mu_1"]*op(1,0)+params["mu_2"]*op(2,0)
                +params["mu_esa_scale"]*params["mu_2"]*op(3,1)
                +params["mu_esa_scale"]*params["mu_1"]*op(3,2))
    model=general.LiouvilleModel.from_hamiltonian(
        dimension=5,hamiltonian=ham,collapse_ops=collapses,
        initial_state=lambda _p:general.vec(op(0,0)),
        transition_dipole=lambda params:mu_plus(params)+mu_plus(params).conj().T,
        dipole_components=lambda params:(mu_plus(params),mu_plus(params).conj().T),
    )
    return model,general.ParameterMap(reference_params=p,controls=())


def _packed(z):
    z=np.asarray(z).ravel()
    return np.r_[z.real,z.imag]


def _cached_pathway_signal_grid(model, parameter_map, lam, omega1_values, omega3_values,
                                pathways, *, tau2, eta):
    """Evaluate the canonical pathway expression while caching shared propagators.

    This is algebraically the same sequence as ``pathway_state_point``.  The
    generic pointwise helper recomputes G1, G3, and U2 for every pathway and
    frequency pair; here those exact matrices are built once per frequency or
    waiting time, which makes publication grids practical.
    """
    params=parameter_map.params(lam)
    L=model.L(params)
    rho=model.rho0(params)
    mu=model.mu(params)
    components=model.mu_components(params)
    u2=model.U(L,tau2)
    sign_rp=general.omega1_sign_for_sector("RP")
    sign_nrp=general.omega1_sign_for_sector("NRP")
    g1={sector:[model.G(L,sign*float(w),eta) for w in omega1_values]
        for sector,sign in (("RP",sign_rp),("NRP",sign_nrp))}
    g3=[model.G(L,-float(w),eta) for w in omega3_values]
    out=np.empty((len(omega3_values)*len(omega1_values),len(pathways)),complex)
    for col,item in enumerate(pathways):
        j1=general.interaction_super(*item.pathway[0],mu=mu,dipole_components=components)
        j2=general.interaction_super(*item.pathway[1],mu=mu,dipole_components=components)
        j3=general.interaction_super(*item.pathway[2],mu=mu,dipole_components=components)
        values=np.empty((len(omega3_values),len(omega1_values)),complex)
        for i3, resolvent3 in enumerate(g3):
            for i1, resolvent1 in enumerate(g1[item.sector]):
                state=resolvent3@j3@u2@j2@resolvent1@j1@rho
                values[i3,i1]=np.trace(mu@general.mat(state,model.dimension))
        out[:,col]=values.reshape(-1)
    return out


def _transported(ref_signals, expansion, lam, weights, order):
    matrix=expansion.evaluate(lam,order=order)
    return ref_signals@(matrix.T@weights)


def _complex_grid(x,n): return np.asarray(x).reshape((n,n))


def _build_fit_data(grid, projection_grid, times, kd, eta, n_quad, order, fit_bound):
    candidate,pmap=_candidate_model()
    from_liouvillian=_jax_liouvillian_from_lambda(pmap)
    derivatives=autodiff.jax_liouvillian_derivatives_from_lambda(
        from_liouvillian,control_dimension=3,liouville_dimension=16,max_order=3)
    truth_model,truth_map=_truth_full_model(kd)
    all_paths=general.canonical_pathways(("RP","NRP"))
    truth_by_time={}
    candidate_reference={}
    expansions={}
    basis_meta={}
    candidate_truth_fn=build_structural_observable(DimerSpectrumConfig(grid,grid,eta=eta),"A")
    truth_fn=build_structural_observable(DimerSpectrumConfig(grid,grid,eta=eta),"C")
    q_truth=np.r_[Q_TRUTH,kd]
    for t in times:
        # Exact active-block RWA truth; the independent five-state path check below
        # confirms this is the same optical observable with a terminal dark sink.
        truth_by_time[float(t)]=np.sum(_cached_pathway_signal_grid(
            truth_model,truth_map,np.array([]),grid,grid,all_paths,tau2=float(t),eta=eta),axis=1).reshape(grid.size,grid.size)
        selected_by_sector=[]; ref_by_sector=[]; expansion_by_sector=[]; joint_weights=[]
        direct_candidate=np.sum(_cached_pathway_signal_grid(
            candidate,pmap,pmap.zero(),grid,grid,all_paths,tau2=float(t),eta=eta),axis=1)
        for sector in ("RP","NRP"):
            sector_paths=[p for p in all_paths if p.sector==sector]
            selected,residuals=general.independent_canonical_pathways(
                candidate,pmap,projection_grid,sector_paths,stage="after_G3",tau2=float(t),eta=eta,rtol=1e-10)
            p_all=pathway_state_grid_matrix(candidate,pmap,pmap.zero(),projection_grid,projection_grid,sector_paths,
                                             tau2=float(t),eta=eta)
            p_sel=pathway_state_grid_matrix(candidate,pmap,pmap.zero(),projection_grid,projection_grid,selected,
                                             tau2=float(t),eta=eta)
            ref_signals=_cached_pathway_signal_grid(candidate,pmap,pmap.zero(),grid,grid,selected,
                                                      tau2=float(t),eta=eta)
            expansion=duhamel_transport_expansion_2d(
                candidate,pmap,projection_grid,projection_grid,selected,liouvillian_derivatives=derivatives,
                tau2=float(t),eta=eta,n_quad=n_quad,max_order=order,rcond=1e-11)
            selected_by_sector.append(selected)
            ref_by_sector.append(ref_signals)
            expansion_by_sector.append(expansion)
            selected_labels={item.label for item in selected}
            dependent_residuals=[float(r) for item,r in zip(sector_paths,residuals,strict=True)
                                 if item.label not in selected_labels]
            joint_weights.append({"sector":sector,"n_canonical":len(sector_paths),
                                  "n_retained":len(selected),
                                  "max_unselected_pathway_residual":max(dependent_residuals,default=0.0)})
        # Fit one reference weight vector across the combined RP+NRP basis so
        # the retained pathways reproduce the full canonical complex sum.
        joined_reference=np.column_stack(ref_by_sector)
        coefficients=np.linalg.pinv(joined_reference,rcond=1e-11)@direct_candidate
        reference_check=joined_reference@coefficients
        reference_observable_error=float(np.linalg.norm(reference_check-direct_candidate)
                                         /max(np.linalg.norm(direct_candidate),1e-30))
        if reference_observable_error>2e-8:
            raise RuntimeError(f"transport reference and direct dimer observable disagree at t={t}: {reference_observable_error:g}")
        offset=0; joint_specs=[]
        for ref_signals,expansion,selected in zip(ref_by_sector,expansion_by_sector,selected_by_sector,strict=True):
            weights=coefficients[offset:offset+ref_signals.shape[1]]
            offset+=ref_signals.shape[1]
            joint_specs.append((ref_signals,expansion,weights))
        candidate_reference[float(t)]=reference_check
        expansions[float(t)]=joint_specs
        basis_meta[float(t)]={"sectors":joint_weights,
                              "reference_observable_relative_error":reference_observable_error}

    # Verify both models and pathway conventions on a tiny subset using the
    # explicit trace-preserving five-state Lindblad propagator.
    sample=np.unique(np.linspace(0,grid.size-1,min(3,grid.size)).round().astype(int))
    check_grid=grid[sample]
    tcheck=float(times[0])
    pcheck=general.canonical_pathways(("RP","NRP"))
    check_paths=pathway_signal_grid(truth_model,truth_map,np.array([]),check_grid,check_grid,
                                    pcheck,tau2=tcheck,eta=eta)
    truth_check=np.sum(check_paths,axis=1).reshape(len(sample),len(sample))
    truth_fast=np.asarray(jax.jit(lambda x:truth_fn(x,tcheck))(jnp.asarray(q_truth)))
    expected=truth_fast[np.ix_(sample,sample)]
    active_error=float(np.linalg.norm(truth_check-expected)/max(np.linalg.norm(expected),1e-30))
    if active_error>2e-8:
        raise RuntimeError(f"full sink and active-block optical responses disagree: {active_error:g}")

    lo=np.asarray([(-.1-Q_TRUTH[0])/Q_SCALES[0],(1e-5-Q_TRUTH[1])/Q_SCALES[1],
                   (1e-5-Q_TRUTH[2])/Q_SCALES[2]])
    hi=np.asarray([(.1-Q_TRUTH[0])/Q_SCALES[0],(.03-Q_TRUTH[1])/Q_SCALES[1],
                   (.04-Q_TRUTH[2])/Q_SCALES[2]])
    lo=np.maximum(lo,-fit_bound); hi=np.minimum(hi,fit_bound)

    def predict(lam,selected_times):
        return {float(t):sum((_transported(ref,exp,lam,w,order)
                             for ref,exp,w in expansions[float(t)]),
                            np.zeros(grid.size*grid.size,complex)).reshape(grid.size,grid.size)
                for t in selected_times}
    target={float(t):truth_by_time[float(t)] for t in times}
    def residual(lam,selected_times):
        z=[_packed(predict(lam,selected_times)[float(t)]-target[float(t)]) for t in selected_times]
        return np.concatenate(z)
    per_time={}
    for t in times:
        result=least_squares(lambda x:residual(x,[float(t)]),np.zeros(3),bounds=(lo,hi),
                             jac="3-point",xtol=2e-9,ftol=2e-9,gtol=2e-9,max_nfev=150)
        per_time[float(t)]={"lambda":result.x,"q":Q_TRUTH+Q_SCALES*result.x,
                           "cost":float(np.dot(result.fun,result.fun)),"success":bool(result.success),
                           "nfev":int(result.nfev),"optimality":float(result.optimality)}
    joint=least_squares(lambda x:residual(x,list(map(float,times))),np.zeros(3),bounds=(lo,hi),
                        jac="3-point",xtol=2e-9,ftol=2e-9,gtol=2e-9,max_nfev=200)
    joint_fit={"lambda":joint.x,"q":Q_TRUTH+Q_SCALES*joint.x,
               "cost":float(np.dot(joint.fun,joint.fun)),"success":bool(joint.success),
               "nfev":int(joint.nfev),"optimality":float(joint.optimality)}
    return {"truth":truth_by_time,"reference":candidate_reference,
            "per_time":per_time,"joint":joint_fit,"prediction":predict(joint.x,list(map(float,times))),
            "per_time_prediction":{t:predict(v["lambda"],[t])[t] for t,v in per_time.items()},
            "basis":basis_meta,"active_block_relative_error":active_error,
            "derivative_keys":[list(k) for k in derivatives]}


def _save_spectrum_figure(data, grid, times, out, q_truth, q_joint, kd, norm):
    truth=data["truth"]; fit=data["prediction"]
    amp=[np.abs(truth[float(t)])/norm for t in times]+[np.abs(fit[float(t)])/norm for t in times]
    vmax=max(float(np.max(a)) for a in amp)
    residual=[(fit[float(t)]-truth[float(t)])/norm for t in times]
    rlim=max(float(np.max(np.abs(z.real))) for z in residual)
    ilim=max(float(np.max(np.abs(z.imag))) for z in residual)
    rlim=max(rlim,1e-30); ilim=max(ilim,1e-30)
    fig,axs=plt.subplots(len(times),4,figsize=(14.6,10.4),constrained_layout=True)
    if len(times)==1: axs=axs[None,:]
    panels=[("Truth $|S|$",lambda t:np.abs(truth[float(t)])/norm,"magma",None,vmax),
            ("Best transported $|S|$",lambda t:np.abs(fit[float(t)])/norm,"magma",None,vmax),
            ("Residual Re",lambda t:((fit[float(t)]-truth[float(t)])/norm).real,"RdBu_r",None,rlim),
            ("Residual Im",lambda t:((fit[float(t)]-truth[float(t)])/norm).imag,"RdBu_r",None,ilim)]
    for row,t in enumerate(times):
        for col,(title,fn,cmap,_norm,lim) in enumerate(panels):
            z=fn(t)
            if col>=2: im=axs[row,col].imshow(z,origin="lower",extent=[grid[0],grid[-1],grid[0],grid[-1]],
                                              interpolation="nearest",aspect="equal",cmap=cmap,
                                              norm=TwoSlopeNorm(vmin=-lim,vcenter=0,vmax=lim))
            else: im=axs[row,col].imshow(z,origin="lower",extent=[grid[0],grid[-1],grid[0],grid[-1]],
                                         interpolation="nearest",aspect="equal",cmap=cmap,vmin=0,vmax=lim)
            if row==0: axs[row,col].set_title(title,loc="left",fontweight="bold")
            axs[row,col].set_ylabel(rf"$t_2={t:g}$; $\omega_3$ (eV)")
            axs[row,col].set_xlabel(r"$\omega_1$ (eV)")
            cb=fig.colorbar(im,ax=axs[row,col],fraction=.046,pad=.03)
            cb.ax.tick_params(labelsize=7)
            cb.set_label("normalized amplitude" if col<2 else "normalized response",fontsize=7)
    fig.suptitle("Dark-state truth and best sink-free Duhamel-transport fit\n"
                 +rf"Truth: $k_d={kd:g}$; joint transport fit: "
                 +rf"$J_{{12}}={q_joint[0]:.4g}$, $k_{{12}}={q_joint[1]:.4g}$, "
                 +rf"$\gamma_\phi={q_joint[2]:.4g}$",fontsize=15,fontweight="bold")
    fig.text(.5,-.01,
             "Truth is the full RP+NRP response of the terminal-sink model. The candidate has no dark state. "
             "A rank-reduced reference pathway basis is weighted to preserve the full canonical sum at the reference; "
             "transport is third-order Duhamel/autodiff. All panels share a single truth-derived L2 normalization.",
             ha="center",fontsize=8)
    fig.savefig(out/"figure_dark_state_truth_vs_best_transported.pdf",bbox_inches="tight")
    fig.savefig(out/"figure_dark_state_truth_vs_best_transported.png",dpi=600,bbox_inches="tight")
    plt.close(fig)


def _save_parameter_figure(data,out,q_truth,times):
    per=data["per_time"]; joint=data["joint"]["q"]
    fig,axs=plt.subplots(1,3,figsize=(11.3,3.8),constrained_layout=True)
    for i,ax in enumerate(axs):
        qhat=np.asarray([per[float(t)]["q"][i] for t in times])
        ax.plot(times,np.full(len(times),q_truth[i]),"k--",lw=1.5,label="dark-truth dimer controls" if i==0 else None)
        ax.plot(times,qhat,"o-",color="#d95f02",lw=1.6,ms=5,label="independent transport fits" if i==0 else None)
        ax.axhline(joint[i],color="#1b9e77",ls=":",lw=2,label="joint transport fit" if i==0 else None)
        ax.set_xlabel(r"waiting time $t_2$")
        ax.set_ylabel(f"{PARAM_NAMES[i]} ({PARAM_UNITS[i]})")
        ax.set_title(chr(65+i),loc="left",fontweight="bold")
        ax.grid(alpha=.25)
    axs[0].legend(frameon=False,fontsize=8,loc="best")
    fig.suptitle("Recovered parameterization under a missing dark-state channel",fontsize=14,fontweight="bold")
    fig.text(.5,-.02,"All fits use the same order-3 Duhamel transport expansion and physical bounds. "
             "Independent fits expose time-dependent apparent parameters; the joint fit uses one global endpoint.",
             ha="center",fontsize=8)
    fig.savefig(out/"figure_dark_state_transport_parameterization.pdf",bbox_inches="tight")
    fig.savefig(out/"figure_dark_state_transport_parameterization.png",dpi=600,bbox_inches="tight")
    plt.close(fig)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--output-dir",type=Path,default=Path("publication_artifacts/dark_state_transport"))
    p.add_argument("--nfreq",type=int,default=21)
    p.add_argument("--projection-nfreq",type=int,default=5,
                   help="frequency grid used to build the Duhamel transport matrix")
    p.add_argument("--omega-min",type=float,default=.90)
    p.add_argument("--omega-max",type=float,default=1.28)
    p.add_argument("--waiting-times",type=float,nargs="+",default=[.2,1.,4.])
    p.add_argument("--eta",type=float,default=.035)
    p.add_argument("--trap-rate",type=float,default=.003)
    p.add_argument("--n-quad",type=int,default=4)
    p.add_argument("--order",type=int,choices=(1,2,3),default=3)
    p.add_argument("--fit-bound",type=float,default=.8)
    args=p.parse_args()
    if args.nfreq<5 or args.projection_nfreq<3: p.error("--nfreq must be at least 5 and --projection-nfreq at least 3")
    if args.trap_rate<0: p.error("--trap-rate must be nonnegative")
    args.output_dir.mkdir(parents=True,exist_ok=True)
    grid=np.linspace(args.omega_min,args.omega_max,args.nfreq)
    projection_grid=np.linspace(args.omega_min,args.omega_max,args.projection_nfreq)
    times=np.asarray(args.waiting_times,float)
    data=_build_fit_data(grid,projection_grid,times,args.trap_rate,args.eta,args.n_quad,args.order,args.fit_bound)
    # Shared normalization preserves signal decay across waiting times while
    # making truth and candidate amplitudes directly comparable.
    powers=[]
